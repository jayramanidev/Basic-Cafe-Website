    <script src="https://unpkg.com/aos@2.3.1/dist/aos.js"></script>
    <script>
        document.addEventListener('DOMContentLoaded', function() {
            lucide.createIcons();
            AOS.init({
                once: true,
                offset: 50,
                duration: 600,
                easing: 'ease-out-cubic',
            });
            
            // Header scroll effect: transforms floating oval pill to full-width rectangle smoothly
            const headerWrapper = document.getElementById('header-wrapper');
            const header = document.getElementById('main-header');
            let isScrolled = null;
            
            function handleScroll() {
                if (!header || !headerWrapper) return;
                const scrolled = window.scrollY > 5;
                
                if (scrolled !== isScrolled) {
                    isScrolled = scrolled;
                    if (isScrolled) {
                        headerWrapper.classList.remove('px-4', 'py-4');
                        headerWrapper.classList.add('px-0', 'py-0');
                        
                        header.classList.remove('max-w-7xl', 'rounded-full');
                        header.classList.add('max-w-none', 'w-full', 'rounded-none', 'shadow-md');
                    } else {
                        headerWrapper.classList.remove('px-0', 'py-0');
                        headerWrapper.classList.add('px-4', 'py-4');
                        
                        header.classList.remove('max-w-none', 'w-full', 'rounded-none', 'shadow-md');
                        header.classList.add('max-w-7xl', 'rounded-full');
                    }
                }
            }
            
            window.addEventListener('scroll', handleScroll, { passive: true });
            handleScroll(); // run on initial load
        });
    </script>
